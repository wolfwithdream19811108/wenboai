    curl_multi_exec($ch, $still_running);
} while ($still_running > 0);

// 关闭所有cURL句柄
foreach ($urls as $url) {
    $curl_handle = curl_init($url);
    curl_multi_remove_handle($ch, $curl_handle);
    curl_close($curl_handle);
